/**
 * Social sharing metadata for the confidential proposal pages under /propostas.
 *
 * Each proposal is shared with its client as a private link (WhatsApp, e-mail),
 * so the link preview has to look like the cover of the document itself — not
 * like the generic platform card from the root layout.
 *
 * Adding a new proposal means adding one entry to `proposalPages`: the route,
 * the metadata (title, description, canonical) and the Open Graph card image
 * are all derived from it. Nothing below is client-specific.
 *
 * Open Graph is for social scrapers; indexing is a separate concern. Every
 * proposal stays `noindex, nofollow` for search engines — see
 * `buildProposalMetadata` and the X-Robots-Tag rules in next.config.ts.
 */

/** Host under which proposals are shared with clients. Mirrors next.config.ts. */
export const PROPOSAL_CANONICAL_ORIGIN = "https://app.onebridgestalwart.com";

/** Route prefix for confidential proposal pages. */
export const PROPOSAL_ROUTE_PREFIX = "/propostas";

/** Brand lockup rendered on every generated share card. */
export const PROPOSAL_SHARE_LOGO_PATH = "public/logo.png";

export interface ProposalPage {
  /** URL segment under /propostas — the public share slug. */
  slug: string;
  /** Client identity, used as the headline of the share card. */
  clientName: string;
  /** Document title and og:title. */
  title: string;
  /** Meta description and og:description. */
  description: string;
  /** Small label above the client name on the share card. */
  eyebrow: string;
  /** One-line scope shown under the client name on the share card. */
  subtitle: string;
  /** Discreet jurisdiction marker at the foot of the share card. */
  jurisdiction: string;
  /** Static document embedded by the page. */
  documentPath: string;
  /** Accessible title for the embedded document. */
  documentTitle: string;
  /**
   * Absolute-from-root path to a hand-made card, when a proposal needs one.
   * Defaults to the card generated by /propostas/<slug>/og.png.
   */
  ogImagePath?: string;
}

