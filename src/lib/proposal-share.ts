export function getProposalPage(slug: string): ProposalPage | undefined {
  return proposalPages.find((page) => page.slug === slug);
}

/** Canonical, absolute URL of the proposal page. */
export function proposalPageUrl(page: ProposalPage): string {
  return `${PROPOSAL_CANONICAL_ORIGIN}${PROPOSAL_ROUTE_PREFIX}/${page.slug}`;
}

/** Absolute, https URL of the Open Graph card. Must resolve without a session. */
export function proposalOgImageUrl(page: ProposalPage): string {
  const imagePath = page.ogImagePath ?? `${PROPOSAL_ROUTE_PREFIX}/${page.slug}/og.png`;
  return `${PROPOSAL_CANONICAL_ORIGIN}${imagePath}`;
}

export const PROPOSAL_OG_IMAGE_SIZE = { width: 1200, height: 630 } as const;

/**
 * Full metadata for a proposal page: per-client Open Graph and Twitter cards,
 * canonical URL, and the unchanged noindex policy.
 */
export function buildProposalMetadata(page: ProposalPage): Metadata {
  const url = proposalPageUrl(page);
  const image = proposalOgImageUrl(page);

  return {
    metadataBase: new URL(PROPOSAL_CANONICAL_ORIGIN),
    // `absolute` keeps the internal platform name out of the client-facing title.
    title: { absolute: page.title },
    description: page.description,
    alternates: {
      canonical: url
    },
    robots: {
      index: false,
      follow: false,
      nocache: true,
      googleBot: {
        index: false,
        follow: false,
        noimageindex: true
      }
    },
    openGraph: {
      type: "website",
      title: page.title,
      description: page.description,
      url,
      siteName: brand.organizationName,
      locale: "pt_BR",
      images: [
        {
          url: image,
          width: PROPOSAL_OG_IMAGE_SIZE.width,
          height: PROPOSAL_OG_IMAGE_SIZE.height,
          type: "image/png",
          alt: page.title
        }
      ]
    },
    twitter: {
      card: "summary_large_image",
      title: page.title,
      description: page.description,
      images: [image]
    }
  };
}
